//! Schema60 keeps schema58's fields but permits consistent inactive and nested
//! shared audio projections that older schema58 readers refused. Schema59 is
//! reserved for an incompatible development layout and is not decoded here.
use crate::{Project, StorageError};
use serde_json::Value;

pub(crate) fn encode(project: &Project) -> Result<Value, StorageError> {
    let mut value = super::nested_audio::encode(project)?;
    value["version"] = 60.into();
    Ok(value)
}
pub(crate) fn decode(bytes: &[u8]) -> Result<Project, StorageError> {
    // Check duplicate keys before the private version projection can collapse them.
    decode_value(super::audio_events::parse_unique(bytes)?)
}
/// Decode an envelope parsed once by [`super::audio_events::parse_unique`].
pub(crate) fn decode_value(mut value: Value) -> Result<Project, StorageError> {
    if value.get("version").and_then(Value::as_u64) != Some(60) {
        return Err(StorageError::Invalid(
            "invalid audio alias projection schema",
        ));
    }
    value["version"] = 58.into();
    super::nested_audio::decode_value(value)
}

#[cfg(test)]
mod tests {
    use super::*;
    use hex_project::{AudioEventEdit, Command, Created, Editor};

    #[test]
    fn prior_schema_migrates_in_memory_and_reserved_layout_is_refused() {
        let mut editor = Editor::new(Project::new(48_000).unwrap(), 8).unwrap();
        let Created::Imported { track, clip, .. } = editor
            .execute(Command::ImportAudioTrack {
                name: "source".into(),
                path: "source.wav".into(),
                sample_rate: 48_000,
                frames: 100,
            })
            .unwrap()
        else {
            panic!("import")
        };
        editor
            .execute(Command::SetTrackColor {
                track,
                color: hex_project::ElementColor::Red,
            })
            .unwrap();
        editor
            .execute(Command::EditAudioEvents {
                clip,
                operation: AudioEventEdit::SetActive {
                    events: vec![1],
                    active: false,
                },
            })
            .unwrap();
        let prior = super::super::nested_audio::encode(editor.project()).unwrap();
        assert_eq!(prior["version"], 58);
        // Generated by the unmodified public schema58 writer at 7a40a9ec;
        // provenance and a reproducible writer live beside the frozen bytes.
        let old =
            include_bytes!("../../tests/fixtures/alias-projection/schema58-inactive-event.json");
        // JSON object key order depends on serde_json feature unification; the
        // frozen historical bytes still exercise the actual migration below.
        let old_value: Value = serde_json::from_slice(old).unwrap();
        assert_eq!(prior, old_value);
        let migrated = crate::decode(old).unwrap();
        assert_eq!(migrated.snapshot(), editor.project().snapshot());
        let current = crate::encode(&migrated).unwrap();
        let mut value: Value = serde_json::from_slice(&current).unwrap();
        assert_eq!(value["version"], crate::CURRENT_SCHEMA_VERSION);
        assert_eq!(
            crate::decode(&current).unwrap().snapshot(),
            migrated.snapshot()
        );
        value["version"] = 59.into();
        let error = crate::decode(&serde_json::to_vec(&value).unwrap())
            .unwrap_err()
            .to_string();
        assert!(error.contains("retain the original"));
    }
}
